    fn id(n: u8) -> CharacterId {
        CharacterId::parse(format!("{n:032x}")).unwrap()
    }

    fn core_with_two() -> (GameCore, CharacterId, CharacterId) {
        let mut core = GameCore::default();
        let first = core
            .create_character(id(1), "alara", BLOOD_ELF_MAGE, START)
            .unwrap();
        let second = core
            .create_character(id(2), "Thalen", BLOOD_ELF_MAGE, START)
            .unwrap();
        (core, first, second)
    }

    #[test]
    fn roster_validates_names_enforces_limit_and_selects_first_character() {
        let mut core = GameCore::default();
        let first = core
            .create_character(id(1), "aLaRa", BLOOD_ELF_MAGE, START)
            .unwrap();
        assert_eq!(core.snapshot(&first).unwrap().name, "Alara");
        assert_eq!(core.selected(), Some(&first));
        assert_eq!(
            core.create_character(id(2), "ALARA", BLOOD_ELF_MAGE, START),
            Err(CoreError::DuplicateName)
        );
        assert_eq!(
            core.create_character(id(2), "A", BLOOD_ELF_MAGE, START),
            Err(CoreError::InvalidName)
        );
        for n in 2..=10 {
            let name = format!("Elf{}", char::from(b'a' + n));
            core.create_character(id(n), &name, BLOOD_ELF_MAGE, START)
                .unwrap();
        }
        assert_eq!(core.character_ids().count(), MAX_CHARACTERS);
        assert_eq!(
            core.create_character(id(11), "Eleven", BLOOD_ELF_MAGE, START),
            Err(CoreError::RosterFull)
        );
    }

    #[test]
    fn selection_entry_movement_time_and_delete_follow_core_authority() {
        let (mut core, first, second) = core_with_two();
        core.select_character(&second).unwrap();
        assert_eq!(core.enter_world().unwrap().id, second);
        let moved = WorldPosition {
            x: 12.0,
            y: 24.0,
            ..START
        };
        core.update_active(moved, 90_000).unwrap();
        let saved = core.leave_world().unwrap();
        assert_eq!(saved.position, moved);
        assert_eq!(saved.play_time_ms, 90_000);
        assert_eq!(saved.game_time_minutes, INITIAL_GAME_TIME_MINUTES + 1);
        assert_eq!(core.snapshot(&first).unwrap().play_time_ms, 0);
        core.delete_character(&second).unwrap();
        assert_eq!(core.selected(), Some(&first));
    }

