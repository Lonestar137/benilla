    #[test]
    fn snapshots_and_profile_round_trip_independently_with_checksums() {
        let (mut core, first, second) = core_with_two();
        core.select_character(&second).unwrap();
        core.enter_world().unwrap();
        core.update_active(WorldPosition { x: 77.0, ..START }, 3_600_000)
            .unwrap();
        core.leave_world().unwrap();

        let profile = decode_profile(&core.encode_profile().unwrap()).unwrap();
        let first_save = decode_snapshot(&core.encode_snapshot(&first).unwrap()).unwrap();
        let second_save = decode_snapshot(&core.encode_snapshot(&second).unwrap()).unwrap();
        let restored = GameCore::restore(profile, [first_save, second_save]).unwrap();
        assert_eq!(restored.selected(), Some(&second));
        assert_eq!(restored.snapshot(&first).unwrap().play_time_ms, 0);
        assert_eq!(restored.snapshot(&second).unwrap().position.x, 77.0);
        assert_eq!(
            restored.snapshot(&second).unwrap().game_time_minutes,
            INITIAL_GAME_TIME_MINUTES + 60
        );
        assert_eq!(
            restored.encode_snapshot(&first).unwrap(),
            core.encode_snapshot(&first).unwrap(),
            "saving another character must not rewrite this snapshot"
        );
    }

    #[test]
    fn checksum_corruption_and_unknown_schema_are_reported() {
        let (core, id, _) = core_with_two();
        let encoded = core.encode_snapshot(&id).unwrap();
        let corrupted = encoded.replace("Alara", "Alira");
        assert_eq!(
            decode_snapshot(&corrupted),
            Err(SaveError::ChecksumMismatch)
        );

        let unsupported = encoded.replace("schema_version = 1", "schema_version = 99");
        assert_eq!(
            decode_snapshot(&unsupported),
            Err(SaveError::UnsupportedVersion(99))
        );
    }

